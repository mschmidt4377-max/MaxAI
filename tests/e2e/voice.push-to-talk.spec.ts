import { expect, test, type Page } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp, selectCoveOption } from './workspace-canvas.helpers'

const VOICE_SAY_LINE = 'You have two agents.'

async function seedClaudeTask(window: Page): Promise<void> {
  await clearAndSeedWorkspace(
    window,
    [
      {
        id: 'task-voice',
        title: 'Voice boss',
        position: { x: 180, y: 140 },
        width: 460,
        height: 280,
        kind: 'task',
        status: null,
        task: {
          requirement: 'Answer voice prompts',
          status: 'todo',
          priority: 'medium',
          tags: [],
          linkedAgentNodeId: null,
          lastRunAt: null,
          autoGeneratedTitle: false,
          createdAt: '2026-10-25T10:00:00.000Z',
          updatedAt: '2026-10-25T10:00:00.000Z',
        },
      },
    ],
    {
      settings: {
        defaultProvider: 'claude-code',
        customModelEnabledByProvider: { 'claude-code': false },
        customModelByProvider: { 'claude-code': '' },
        customModelOptionsByProvider: { 'claude-code': [] },
      },
    },
  )
}

async function chooseVoiceBoss(window: Page, bossNodeId: string): Promise<void> {
  await window.locator('[data-testid="app-header-settings"]').click({ noWaitAfter: true })
  const dialog = window.getByTestId('settings-panel')
  await expect(dialog).toBeVisible()
  await dialog.getByTestId('settings-section-nav-agent').click()
  await dialog.getByTestId('settings-agent-tab-voice').click()
  await dialog.getByTestId('settings-voice-enabled').click()
  await selectCoveOption(window, 'settings-voice-boss', bossNodeId)
  await window.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
}

async function holdPushToTalk(window: Page, holdMs: number): Promise<void> {
  await window.keyboard.down('Alt')
  await window.keyboard.down('KeyX')
  await window.waitForTimeout(holdMs)
  await window.keyboard.up('KeyX')
  await window.keyboard.up('Alt')
}

test.describe('Voice - push to talk', () => {
  test('sends the transcript to the boss and speaks its SAY line', async () => {
    const { electronApp, window } = await launchApp({
      windowMode: 'inactive',
      env: {
        OPENCOVE_TEST_VOICE_ENGINE: 'stub',
        OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-hook-voice-reply',
        OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
      },
    })
    try {
      await seedClaudeTask(window)
      await window
        .locator('.task-node')
        .first()
        .locator('[data-testid="task-node-run-agent"]')
        .click()
      const agentNode = window.locator('.terminal-node').first()
      await expect(agentNode).toContainText('[opencove-test-voice] ready')
      const bossNodeId = await window
        .locator('.react-flow__node:has(.terminal-node)')
        .first()
        .getAttribute('data-id')
      expect(bossNodeId).toBeTruthy()

      await chooseVoiceBoss(window, bossNodeId as string)
      const indicator = window.getByTestId('voice-indicator')

      // A tap shorter than the minimum hold is cancelled and sends nothing.
      await holdPushToTalk(window, 50)
      await expect(indicator).toHaveAttribute('data-voice-phase', 'cancelled')

      await holdPushToTalk(window, 600)
      await expect(agentNode).toContainText(
        '[opencove-test-voice] prompt: list the agents (Voice request:',
      )
      await expect(agentNode).toContainText('[opencove-test-voice] replied')
      await expect
        .poll(async () => await electronApp.evaluate(() => globalThis.__opencoveTestVoiceSpoken))
        .toEqual([VOICE_SAY_LINE])
      await expect(indicator).toHaveCount(0)

      // The spoken reply announces the finish, so the boss raises no standby banner.
      await expect(window.locator('[data-testid^="app-notification-"]')).toHaveCount(0)
    } finally {
      await electronApp.close()
    }
  })
})
